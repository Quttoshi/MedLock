#!/usr/bin/env python3
"""
Give a patient account a year of realistic lab results, for demos and for building
the Health trends screens.

About a dozen PDF reports from three labs (Chughtai, Excel Labs, IDC) are generated and
uploaded through the real upload pipeline: encrypted, stored, read by the parser and
turned into lab results, exactly like a patient's own upload. The story they tell:
iron-deficiency anaemia improving on treatment, HbA1c crossing into the diabetes range
and coming back down, LDL falling, low vitamin D corrected, creatinine creeping up.

The PDFs say "Sample report generated by MedLock" and their file names start with
"medlock-sample-", which is how --remove finds them again.

Usage (from the backend/ directory):
  python scripts/load_sample_results.py --email patient@example.com
  python scripts/load_sample_results.py --email patient@example.com --remove
  python scripts/load_sample_results.py --email patient@example.com --save-pdfs out/   # also keep copies

Blockchain events and upload notifications/emails are skipped unless --with-blockchain
or --notify is given.
"""
import argparse
import io
import sys
from datetime import date
from pathlib import Path
from types import SimpleNamespace

# Allow importing from backend/app
sys.path.insert(0, str(Path(__file__).parent.parent))

from dotenv import load_dotenv
load_dotenv(Path(__file__).parent.parent / ".env")

from fastapi import HTTPException  # noqa: E402
from sqlalchemy import func  # noqa: E402

from app.database import SessionLocal  # noqa: E402
import app.models  # noqa: E402,F401  (registers every model)
from app.models.medical_report import MedicalReport  # noqa: E402
from app.models.patient import Patient  # noqa: E402
from app.models.user import User  # noqa: E402
from app.services import report_service  # noqa: E402
from app.services import sample_reports as samples  # noqa: E402
from app.services.health_analysis_service import age_on  # noqa: E402
from app.services.storage_service import delete_file  # noqa: E402


def _find_patient(db, email: str):
    user = db.query(User).filter(func.lower(User.email) == email.lower()).first()
    if not user:
        return None, None
    return user, db.query(Patient).filter(Patient.user_id == user.id).first()


def _remove(db, patient) -> None:
    reports = db.query(MedicalReport).filter(
        MedicalReport.patient_id == patient.id,
        MedicalReport.original_filename.like(f"{samples.SAMPLE_PREFIX}%"),
    ).all()
    for report in reports:
        try:
            delete_file(report.file_url)
        except Exception as exc:
            print(f"  could not delete stored file for {report.original_filename}: {exc}")
        db.delete(report)
    db.commit()
    print(f"Removed {len(reports)} sample report(s) and their results.")


def _load(db, user, patient, args) -> int:
    if not args.with_blockchain:
        report_service.blockchain_log = lambda *a, **kw: None
    if not args.notify:
        report_service.create_notification = lambda *a, **kw: None

    sex = patient.gender if patient.gender in ("male", "female") else None
    age = age_on(patient.date_of_birth, date.today())
    if sex is None or age is None:
        print("Note: the patient has no sex or date of birth on their profile, so eGFR cannot be "
              "calculated and standard ranges are less specific. Add them in the profile to see everything.")

    save_dir = Path(args.save_pdfs) if args.save_pdfs else None
    if save_dir:
        save_dir.mkdir(parents=True, exist_ok=True)

    loaded = 0
    for sample in samples.year_of_results(sex):
        pdf = samples.render_pdf(sample, user.full_name or "Patient", age, sex)
        if save_dir:
            (save_dir / sample.filename).write_bytes(pdf)
        upload = SimpleNamespace(content_type="application/pdf", filename=sample.filename, file=io.BytesIO(pdf))
        try:
            report = report_service.upload_report(upload, sample.report_type, user, db)
        except HTTPException as exc:
            print(f"  {sample.filename}: {exc.detail}")
            continue
        count = len(report.lab_results)
        expected = len(sample.rows)
        note = "" if count == expected else f"  (expected {expected}; check the parser)"
        print(f"  {sample.collected_on}  {samples.LABS[sample.lab]['lab_name']:<28} {sample.title:<36} {count} result(s){note}")
        loaded += 1
    print(f"Loaded {loaded} report(s). Open Health trends as {user.email} to see them.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Load a year of sample lab results for a patient")
    parser.add_argument("--email", required=True, help="the patient's account email")
    parser.add_argument("--remove", action="store_true", help="remove the sample reports loaded earlier")
    parser.add_argument("--with-blockchain", action="store_true", help="also log uploads on the blockchain (slow)")
    parser.add_argument("--notify", action="store_true", help="also send the usual upload notifications and emails")
    parser.add_argument("--save-pdfs", metavar="DIR", help="also save the generated PDFs in this folder")
    args = parser.parse_args()

    db = SessionLocal()
    try:
        user, patient = _find_patient(db, args.email)
        if not user:
            print(f"No account with email {args.email}")
            return 1
        if not patient:
            print(f"{args.email} is not a patient account")
            return 1
        if args.remove:
            _remove(db, patient)
            return 0
        return _load(db, user, patient, args)
    finally:
        db.close()


if __name__ == "__main__":
    sys.exit(main())
